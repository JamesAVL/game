def glyph_for(ch):
    if ch in G:
        return G[ch]
    up = ch.upper()
    if up in G:
        return G[up]
    return G["?"]


def scale2x(grid):
    """EPX/Scale2x: double a 1-bit glyph while smoothing diagonal staircases."""
    h = len(grid); w = len(grid[0])
    def at(y, x):
        return 0 <= y < h and 0 <= x < w and grid[y][x] == "#"
    out = [[False] * (w * 2) for _ in range(h * 2)]
    for y in range(h):
        for x in range(w):
            e = at(y, x)
            b = at(y - 1, x); d = at(y, x - 1); f = at(y, x + 1); g = at(y + 1, x)
            if b != g and d != f:
                e0 = d if d == b else e
                e1 = f if b == f else e
                e2 = d if d == g else e
                e3 = f if g == f else e
            else:
                e0 = e1 = e2 = e3 = e
            out[y * 2][x * 2] = e0;     out[y * 2][x * 2 + 1] = e1
            out[y * 2 + 1][x * 2] = e2; out[y * 2 + 1][x * 2 + 1] = e3
    return out


def scale3x(grid):
    """EPX/Scale3x: triple a 1-bit glyph while smoothing diagonal staircases."""
    h = len(grid); w = len(grid[0])
    def at(y, x):
        return 0 <= y < h and 0 <= x < w and grid[y][x] == "#"
    out = [[False] * (w * 3) for _ in range(h * 3)]
    for y in range(h):
        for x in range(w):
            A = at(y - 1, x - 1); B = at(y - 1, x); C = at(y - 1, x + 1)
            D = at(y, x - 1);     E = at(y, x);     F = at(y, x + 1)
            Gg = at(y + 1, x - 1); H = at(y + 1, x); I = at(y + 1, x + 1)
            if B != H and D != F:
                e0 = D if D == B else E
                e1 = B if ((D == B and E != C) or (B == F and E != A)) else E
                e2 = F if B == F else E
                e3 = D if ((D == B and E != Gg) or (D == H and E != A)) else E
                e4 = E
                e5 = F if ((B == F and E != I) or (H == F and E != C)) else E
                e6 = D if D == H else E
                e7 = H if ((D == H and E != I) or (H == F and E != Gg)) else E
                e8 = F if H == F else E
            else:
                e0 = e1 = e2 = e3 = e4 = e5 = e6 = e7 = e8 = E
            by, bx = y * 3, x * 3
            out[by][bx], out[by][bx + 1], out[by][bx + 2] = e0, e1, e2
            out[by + 1][bx], out[by + 1][bx + 1], out[by + 1][bx + 2] = e3, e4, e5
            out[by + 2][bx], out[by + 2][bx + 1], out[by + 2][bx + 2] = e6, e7, e8
    return out


def build(out_path):
    n = LAST - FIRST + 1
    rows = (n + COLS - 1) // COLS
    cv = Canvas(COLS * CELL_W, rows * CELL_H, scale=1)  # author natively at ART res
    for i in range(n):
        ch = chr(FIRST + i)
        cx = (i % COLS) * CELL_W
        cy = (i // COLS) * CELL_H
        big = scale3x(glyph_for(ch))   # 15x21
        for ry, row in enumerate(big):
            for rx, on in enumerate(row):
                if on:
                    cv.set(cx + rx, cy + ry, (255, 255, 255, 255))
    cv.write(out_path)
    print("wrote", out_path)


