def glyph_for(ch):
    if ch in G:
        return G[ch]
    up = ch.upper()
    if up in G:
        return G[up]
    return G["?"]


def build(out_path):
    n = LAST - FIRST + 1
    rows = (n + COLS - 1) // COLS
    cv = Canvas(COLS * CELL_W, rows * CELL_H)
    for i in range(n):
        ch = chr(FIRST + i)
        cx = (i % COLS) * CELL_W
        cy = (i // COLS) * CELL_H
        grid = glyph_for(ch)
        for ry, row in enumerate(grid):
            for rx, c in enumerate(row):
                if c == "#":
                    cv.set(cx + rx, cy + ry, (255, 255, 255, 255))
    cv.write(out_path)
    print("wrote", out_path)


if __name__ == "__main__":
    here = os.path.dirname(__file__)
    out = os.path.join(here, "..", "assets", "ui", "font.png")
    build(out)
